<script>
document.addEventListener('DOMContentLoaded', function() {
    const track = document.querySelector('.testimonial-track');
    const items = document.querySelectorAll('.testimonial-item');
    const dots = document.querySelectorAll('.dot');
    const prevBtn = document.querySelector('.prev-btn');
    const nextBtn = document.querySelector('.next-btn');
    const container = document.querySelector('.carousel-container');
    
    let currentSlide = 0;
    const totalSlides = items.length;
    let isTransitioning = false;
    let autoPlayInterval;
    let startX = 0;
    let currentX = 0;
    let isDragging = false;
    
    // Responsive dimensions
    const getDimensions = () => {
        const w = window.innerWidth;
        if (w <= 360) return { itemWidth: 420, gap: 10 };
        if (w <= 480) return { itemWidth: 504, gap: 12 };
        if (w <= 768) return { itemWidth: 590, gap: 15 };
        if (w <= 992) return { itemWidth: 672, gap: 16 };
        if (w <= 1200) return { itemWidth: 748, gap: 18 };
        return { itemWidth: 860, gap: 20 };
    };
    
    const updateCarousel = () => {
        if (isTransitioning) return;
        isTransitioning = true;
        
        const dim = getDimensions();
        const centerOffset = (container.offsetWidth - (dim.itemWidth - dim.gap)) / 2;
        const translateValue = -(currentSlide * dim.itemWidth) + centerOffset;
        
        track.style.transform = `translateX(${translateValue}px)`;
        
        items.forEach((item, index) => {
            item.classList.toggle('active', index === currentSlide);
        });
        
        dots.forEach((dot, index) => {
            dot.classList.toggle('active', index === currentSlide);
        });
        
        setTimeout(() => isTransitioning = false, 500);
    };
    
    const nextSlide = () => {
        if (isTransitioning) return;
        currentSlide = (currentSlide + 1) % totalSlides;
        updateCarousel();
    };
    
    const prevSlide = () => {
        if (isTransitioning) return;
        currentSlide = (currentSlide - 1 + totalSlides) % totalSlides;
        updateCarousel();
    };
    
    const goToSlide = (index) => {
        if (isTransitioning || index === currentSlide) return;
        currentSlide = index;
        updateCarousel();
    };
    
    const startAutoPlay = () => {
        const speed = window.innerWidth <= 768 ? 7000 : 6000;
        autoPlayInterval = setInterval(nextSlide, speed);
    };
    
    const stopAutoPlay = () => clearInterval(autoPlayInterval);
    
    const getEventX = (e) => e.type.includes('mouse') ? e.clientX : e.touches[0].clientX;
    
    const handleStart = (e) => {
        if (isTransitioning) return;
        isDragging = true;
        startX = getEventX(e);
        currentX = startX;
        track.style.transition = 'none';
        stopAutoPlay();
        
        if (e.type.includes('touch')) e.preventDefault();
        if (e.type === 'mousedown') {
            document.addEventListener('mousemove', handleMove);
            document.addEventListener('mouseup', handleEnd);
            e.preventDefault();
        }
    };
    
    const handleMove = (e) => {
        if (!isDragging) return;
        e.preventDefault();
        currentX = getEventX(e);
        
        const deltaX = currentX - startX;
        const dim = getDimensions();
        const centerOffset = (container.offsetWidth - (dim.itemWidth - dim.gap)) / 2;
        const baseTranslate = -(currentSlide * dim.itemWidth) + centerOffset;
        
        track.style.transform = `translateX(${baseTranslate + deltaX * 0.3}px)`;
    };
    
    const handleEnd = (e) => {
        if (!isDragging) return;
        isDragging = false;
        
        const deltaX = currentX - startX;
        const threshold = window.innerWidth <= 480 ? 60 : window.innerWidth <= 768 ? 70 : 80;
        
        track.style.transition = 'transform 0.5s cubic-bezier(0.25, 0.46, 0.45, 0.94)';
        
        if (Math.abs(deltaX) > threshold) {
            deltaX > 0 ? prevSlide() : nextSlide();
        } else {
            updateCarousel();
        }
        
        if (e.type === 'mouseup') {
            document.removeEventListener('mousemove', handleMove);
            document.removeEventListener('mouseup', handleEnd);
        }
        
        setTimeout(startAutoPlay, 1000);
    };
    
    // Event listeners
    nextBtn.addEventListener('click', (e) => {
        e.preventDefault();
        nextSlide();
        stopAutoPlay();
        setTimeout(startAutoPlay, 2000);
    });
    
    prevBtn.addEventListener('click', (e) => {
        e.preventDefault();
        prevSlide();
        stopAutoPlay();
        setTimeout(startAutoPlay, 2000);
    });
    
    items.forEach((item, index) => {
        item.addEventListener('click', (e) => {
            e.preventDefault();
            if (index !== currentSlide) {
                goToSlide(index);
                stopAutoPlay();
                setTimeout(startAutoPlay, 2000);
            }
        });
        
        item.addEventListener('touchstart', () => {
            item.style.transform = item.classList.contains('active') ? 'scale(1.01)' : 'scale(0.88)';
        });
        
        item.addEventListener('touchend', () => {
            setTimeout(() => {
                item.style.transform = item.classList.contains('active') ? 'scale(1)' : 'scale(0.85)';
            }, 100);
        });
    });
    
    dots.forEach((dot, index) => {
        dot.addEventListener('click', (e) => {
            e.preventDefault();
            goToSlide(index);
            stopAutoPlay();
            setTimeout(startAutoPlay, 2000);
        });
    });
    
    // Touch and mouse events
    container.addEventListener('touchstart', handleStart, { passive: false });
    container.addEventListener('touchmove', handleMove, { passive: false });
    container.addEventListener('touchend', handleEnd, { passive: false });
    container.addEventListener('mousedown', handleStart);
    container.addEventListener('contextmenu', e => e.preventDefault());
    
    // Hover pause (desktop only)
    if (window.innerWidth > 768) {
        container.addEventListener('mouseenter', stopAutoPlay);
        container.addEventListener('mouseleave', startAutoPlay);
    }
    
    // Resize and orientation handling
    let resizeTimeout;
    const handleResize = () => {
        clearTimeout(resizeTimeout);
        resizeTimeout = setTimeout(() => {
            updateCarousel();
            stopAutoPlay();
            setTimeout(startAutoPlay, 1000);
        }, 250);
    };
    
    window.addEventListener('resize', handleResize);
    window.addEventListener('orientationchange', () => setTimeout(handleResize, 300));
    
    // Visibility handling
    document.addEventListener('visibilitychange', () => {
        document.hidden ? stopAutoPlay() : startAutoPlay();
    });
    
    // Initialize
    updateCarousel();
    startAutoPlay();
});
</script>