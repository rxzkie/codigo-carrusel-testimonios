<script>
document.addEventListener('DOMContentLoaded', function() {
    const track = document.querySelector('.testimonial-track');
    const items = document.querySelectorAll('.testimonial-item');
    const dots = document.querySelectorAll('.dot');
    const prevBtn = document.querySelector('.prev-btn');
    const nextBtn = document.querySelector('.next-btn');
    const container = document.querySelector('.carousel-container');
    
    let currentSlide = 0;
    const totalSlides = items.length;
    let isTransitioning = false;
    let autoPlayInterval;
    let startX = 0;
    let currentX = 0;
    let isDragging = false;
    
    const updateCarousel = () => {
        if (isTransitioning) return;
        isTransitioning = true;
        
        const containerWidth = container.offsetWidth;
        const itemWidth = containerWidth - 40;
        const gap = 40;
        const translateValue = -currentSlide * (itemWidth + gap);
        
        track.style.transform = `translateX(${translateValue}px)`;
        track.style.width = `${(itemWidth + gap) * totalSlides}px`;
        
        items.forEach((item, index) => {
            item.classList.toggle('active', index === currentSlide);
            item.style.flex = `0 0 ${itemWidth}px`;
        });
        
        dots.forEach((dot, index) => {
            dot.classList.toggle('active', index === currentSlide);
        });
        
        setTimeout(() => isTransitioning = false, 500);
    };
    
    const nextSlide = () => {
        if (isTransitioning) return;
        currentSlide = (currentSlide + 1) % totalSlides;
        updateCarousel();
    };
    
    const prevSlide = () => {
        if (isTransitioning) return;
        currentSlide = (currentSlide - 1 + totalSlides) % totalSlides;
        updateCarousel();
    };
    
    const goToSlide = (index) => {
        if (isTransitioning || index === currentSlide) return;
        currentSlide = index;
        updateCarousel();
    };
    
    const startAutoPlay = () => {
        stopAutoPlay();
        autoPlayInterval = setInterval(nextSlide, 15000);
    };
    
    const stopAutoPlay = () => {
        if (autoPlayInterval) {
            clearInterval(autoPlayInterval);
            autoPlayInterval = null;
        }
    };
    
    const getEventX = (e) => e.type.includes('mouse') ? e.clientX : e.touches[0].clientX;
    
    const handleStart = (e) => {
        if (isTransitioning) return;
        if (e.target.closest('.nav-btn') || e.target.closest('.dot') || e.target.closest('.carousel-nav') || e.target.closest('.carousel-dots')) return;
        isDragging = true;
        startX = getEventX(e);
        currentX = startX;
        track.style.transition = 'none';
        stopAutoPlay();
        
        if (e.type.includes('touch')) e.preventDefault();
        if (e.type === 'mousedown') {
            document.addEventListener('mousemove', handleMove);
            document.addEventListener('mouseup', handleEnd);
            e.preventDefault();
        }
    };
    
    const handleMove = (e) => {
        if (!isDragging) return;
        e.preventDefault();
        currentX = getEventX(e);
        
        const deltaX = currentX - startX;
        const containerWidth = container.offsetWidth;
        const itemWidth = containerWidth - 40;
        const gap = 40;
        const baseTranslate = -currentSlide * (itemWidth + gap);
        const dragOffset = deltaX * 0.3;
        
        track.style.transform = `translateX(${baseTranslate + dragOffset}px)`;
    };
    
    const handleEnd = (e) => {
        if (!isDragging) return;
        isDragging = false;
        
        const deltaX = currentX - startX;
        const threshold = container.offsetWidth * 0.15;
        
        track.style.transition = 'transform 0.5s cubic-bezier(0.25, 0.46, 0.45, 0.94)';
        
        if (Math.abs(deltaX) > threshold) {
            deltaX > 0 ? prevSlide() : nextSlide();
        } else {
            updateCarousel();
        }
        
        if (e.type === 'mouseup') {
            document.removeEventListener('mousemove', handleMove);
            document.removeEventListener('mouseup', handleEnd);
        }
        
        setTimeout(startAutoPlay, 1000);
    };
    
    if (nextBtn) {
        const handleNextClick = (e) => {
            e.preventDefault();
            e.stopPropagation();
            if (!isTransitioning) {
                stopAutoPlay();
                nextSlide();
                setTimeout(startAutoPlay, 2000);
            }
        };
        
        nextBtn.addEventListener('click', handleNextClick);
        nextBtn.addEventListener('touchend', handleNextClick);
        
        nextBtn.addEventListener('touchstart', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
        
        nextBtn.addEventListener('touchmove', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
        
        nextBtn.addEventListener('mousedown', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
    }
    
    if (prevBtn) {
        const handlePrevClick = (e) => {
            e.preventDefault();
            e.stopPropagation();
            if (!isTransitioning) {
                stopAutoPlay();
                prevSlide();
                setTimeout(startAutoPlay, 2000);
            }
        };
        
        prevBtn.addEventListener('click', handlePrevClick);
        prevBtn.addEventListener('touchend', handlePrevClick);
        
        prevBtn.addEventListener('touchstart', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
        
        prevBtn.addEventListener('touchmove', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
        
        prevBtn.addEventListener('mousedown', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
    }
    
    items.forEach((item, index) => {
        item.addEventListener('click', (e) => {
            e.preventDefault();
            if (index !== currentSlide && !isTransitioning) {
                stopAutoPlay();
                goToSlide(index);
                setTimeout(startAutoPlay, 2000);
            }
        });
    });
    
    dots.forEach((dot, index) => {
        const handleDotClick = (e) => {
            e.preventDefault();
            e.stopPropagation();
            if (!isTransitioning) {
                stopAutoPlay();
                goToSlide(index);
                setTimeout(startAutoPlay, 2000);
            }
        };
        
        dot.addEventListener('click', handleDotClick);
        dot.addEventListener('touchend', handleDotClick);
        
        dot.addEventListener('touchstart', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
        
        dot.addEventListener('touchmove', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
        
        dot.addEventListener('mousedown', (e) => {
            e.preventDefault();
            e.stopPropagation();
        });
    });
    
    container?.addEventListener('touchstart', handleStart, { passive: false });
    container?.addEventListener('touchmove', handleMove, { passive: false });
    container?.addEventListener('touchend', handleEnd, { passive: false });
    container?.addEventListener('mousedown', handleStart);
    container?.addEventListener('contextmenu', e => e.preventDefault());
    
    if (window.innerWidth > 768 && !('ontouchstart' in window)) {
        container?.addEventListener('mouseenter', stopAutoPlay);
        container?.addEventListener('mouseleave', startAutoPlay);
    }
    
    let resizeTimeout;
    window.addEventListener('resize', () => {
        clearTimeout(resizeTimeout);
        resizeTimeout = setTimeout(() => {
            updateCarousel();
            stopAutoPlay();
            setTimeout(startAutoPlay, 1000);
        }, 250);
    });
    
    window.addEventListener('orientationchange', () => {
        setTimeout(() => {
            updateCarousel();
            stopAutoPlay();
            setTimeout(startAutoPlay, 1000);
        }, 300);
    });
    
    document.addEventListener('visibilitychange', () => {
        document.hidden ? stopAutoPlay() : startAutoPlay();
    });
    
    if (items.length > 0 && track && container) {
        updateCarousel();
        startAutoPlay();
    }
});
